/* Generates the demo registry and demo metadata from src/components/demos/*.tsx.
   - src/components/demos/registry.tsx   client-side lazy loaders, keyed by PascalCase file name
   - src/data/demo-meta.generated.ts     server-safe: source path + libraries / Web APIs each demo uses
   Run via `pnpm run gen` (also runs before dev/build). Do not edit the outputs by hand. */

import fs from "node:fs";
import path from "node:path";

const DIR = "src/components/demos";
const files = fs
  .readdirSync(DIR)
  .filter((f) => f.endsWith(".tsx") && f !== "registry.tsx" && !f.startsWith("_"))
  .sort();

const pascal = (f) =>
  path
    .basename(f, ".tsx")
    .split("-")
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");

const LIBS = [
  ["recharts", /from "recharts"/],
  ["motion", /from "motion\//],
  ["canvas-confetti", /from "canvas-confetti"/],
  ["cmdk", /from "cmdk"/],
  ["react-hook-form", /from "react-hook-form"/],
  ["zod", /from "zod"/],
  ["sonner", /from "sonner"/],
  ["shadcn/ui", /from "@\/components\/ui\//],
  ["lucide-react", /from "lucide-react"/],
];
const APIS = [
  ["Clipboard API", /navigator\.clipboard/],
  ["Web Storage", /localStorage|sessionStorage/],
  ["matchMedia", /matchMedia\(/],
  ["IntersectionObserver", /IntersectionObserver/],
  ["ResizeObserver", /ResizeObserver/],
  ["requestAnimationFrame", /requestAnimationFrame/],
  ["Canvas 2D", /getContext\(["']2d/],
  ["SVG", /<svg/],
  ["Pointer Events", /onPointer(Down|Move|Up)/],
  ["Drag and Drop", /onDrag(Start|Over|End)|onDrop=/],
  ["Vibration API", /navigator\.vibrate/],
  ["Geolocation API", /navigator\.geolocation/],
  ["Notifications API", /Notification\./],
  ["View Transitions API", /startViewTransition/],
  ["Web Share API", /navigator\.share/],
  ["Speech Synthesis", /speechSynthesis/],
  ["Fullscreen API", /requestFullscreen/],
  ["File API", /FileReader|URL\.createObjectURL/],
  ["CSS scroll-driven animations", /animation-timeline|animationTimeline/],
  ["CSS scroll snap", /snap-(x|y|mandatory|start|center)/],
];

const meta = {};
let reg = `"use client";

// Generated by scripts/gen-demos.mjs — do not edit.

import dynamic from "next/dynamic";
import type { ComponentType } from "react";
import { DemoSkeleton } from "./_skeleton";

const d = (loader: () => Promise<{ default: ComponentType }>) =>
  dynamic(loader, { ssr: false, loading: DemoSkeleton });

export const demoRegistry: Record<string, ComponentType> = {
`;
for (const f of files) {
  const key = pascal(f);
  const src = fs.readFileSync(path.join(DIR, f), "utf8");
  const libs = LIBS.filter(([, re]) => re.test(src)).map(([n]) => n);
  const apis = APIS.filter(([, re]) => re.test(src)).map(([n]) => n);
  meta[key] = { file: `${DIR}/${f}`, libs, apis, lines: src.split("\n").length };
  reg += `  ${key}: d(() => import("./${path.basename(f, ".tsx")}")),\n`;
}
reg += `};\n`;

const metaTs = `// Generated by scripts/gen-demos.mjs — do not edit.

export type DemoMeta = { file: string; libs: string[]; apis: string[]; lines: number };

export const demoMeta: Record<string, DemoMeta> = ${JSON.stringify(meta, null, 2)};
`;

fs.writeFileSync(path.join(DIR, "registry.tsx"), reg);
fs.writeFileSync("src/data/demo-meta.generated.ts", metaTs);
console.log(`[demos] ${files.length} demos`);
